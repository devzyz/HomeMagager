import { test, expect } from '@playwright/test'
import { login } from './helpers'

for (const viewport of [{ width: 1280, height: 900 }, { width: 390, height: 844 }]) {
  test(`工资成员、每日工时和月历颜色 ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await login(page)
    await page.getByRole('link', { name: '工资', exact: true }).click()
    await page.getByRole('button', { name: '新增成员', exact: true }).click()
    const memberName = `工资测试-${viewport.width}`
    await page.getByLabel('姓名', { exact: true }).fill(memberName)
    await page.getByLabel('时薪（元 / 小时）', { exact: true }).fill('25.50')
    await page.getByRole('button', { name: '保存成员' }).click()
    await page.getByRole('link', { name: new RegExp(memberName) }).click()
    await expect(page.getByRole('heading', { name: memberName })).toBeVisible()
    const today = await page.locator('.day-cell.today').getAttribute('data-date')
    expect(today).toBeTruthy()
    const day = page.locator(`[data-date="${today}"]`)
    await day.click()
    await page.getByLabel('上班时长（小时）', { exact: true }).fill('7.5')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(day).toHaveClass(/worked/)
    await expect(day).toContainText('191.25')
    expect(await day.locator('.day-amount').evaluate((element) => {
      const range = document.createRange()
      range.selectNodeContents(element)
      return range.getClientRects().length
    })).toBe(1)
    await expect(page.locator('.summary')).toContainText('191.25')
    await page.reload()
    await expect(day).toContainText('191.25')
    await day.click()
    await page.getByRole('dialog').locator('label').filter({ hasText: '请假' }).click()
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(day).toHaveClass(/leave/)
    await expect(page.locator('.summary')).toContainText('0.00')
    await day.click()
    await page.getByRole('button', { name: '清除记录', exact: true }).click()
    await expect(day).toHaveClass(/unrecorded/)
    await day.click()
    await page.getByLabel('上班时长（小时）', { exact: true }).fill('8')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(day).toHaveClass(/worked/)
    const other = page.locator('.day-cell.unrecorded').first()
    if (await other.count()) {
      await other.click()
      await page.getByRole('dialog').locator('label').filter({ hasText: '请假' }).click()
      await page.getByRole('button', { name: '保存', exact: true }).click()
      await expect(page.locator('.day-cell.leave')).toHaveCount(1)
    }
    await expect(page.locator('.calendar-grid')).toBeVisible()
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await expect(page.locator('.el-message')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/payroll-${viewport.width}.png`, fullPage: true })

    await page.getByRole('link', { name: '返回人员列表' }).click()
    await page.getByRole('button', { name: `编辑${memberName}资料`, exact: true }).click()
    await page.getByLabel('时薪（元 / 小时）', { exact: true }).fill('30')
    await page.getByRole('button', { name: '保存成员' }).click()
    await page.getByRole('link', { name: new RegExp(memberName) }).click()
    await expect(day).toContainText('204')
    await day.click()
    await expect(page.getByLabel('当天时薪（元 / 小时）', { exact: true })).toHaveValue('25.50')
    await page.getByRole('button', { name: '取消', exact: true }).click()

    await page.getByRole('button', { name: '下个月', exact: true }).click()
    const future = page.locator('.day-cell').first()
    await expect(future).toHaveClass(/future/)
    await future.click()
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(future).toHaveClass(/future/)
    await expect(future).toContainText('预记')
    await expect(page.locator('.summary')).toContainText('0.00')
    await page.getByRole('button', { name: '本月', exact: true }).click()
    await expect(day).toHaveClass(/worked/)
  })
}
